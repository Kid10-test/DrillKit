import puppeteer from 'puppeteer'
const wait = (ms) => new Promise((r) => setTimeout(r, ms))
const b = await puppeteer.launch({ headless: 'new', args: ['--no-sandbox','--mute-audio'] })
const p = await b.newPage(); await p.setViewport({ width: 1440, height: 1000 })
const errs = []; p.on('pageerror', e => errs.push(e.message.slice(0,160)))
const posisi = () => p.evaluate(() => [...document.querySelectorAll('circle[data-titik="1"]')].map(c => [Number(c.getAttribute('cx')), Number(c.getAttribute('cy'))]))
const tombol = (t) => p.evaluate((x)=>{ const el=[...document.querySelectorAll('button')].find(y=>y.textContent.trim()===x); if(!el) return false; el.click(); return true }, t)
const hitung = (a,c) => a.reduce((n,q,i)=>n+(Math.hypot(q[0]-c[i][0], q[1]-c[i][1])>0.02?1:0),0)
await p.goto('http://localhost:5173/', { waitUntil: 'networkidle2' }); await wait(1600)
await p.evaluate(() => { const x=[...document.querySelectorAll('button')].find(y=>y.textContent.includes('Muat data contoh')); x&&x.click() })
await wait(3400); await p.evaluate(() => { location.hash = '#/drill' }); await wait(2800)
const A = await posisi()
const ling = await p.$$('circle[data-titik="1"]')
// pilih 3 titik: klik, lalu shift+klik dua lagi
await ling[0].click(); await wait(400)
await p.keyboard.down('Shift'); await ling[1].click(); await wait(300); await ling[2].click(); await p.keyboard.up('Shift'); await wait(500)
const teks = await p.evaluate(() => { const el=[...document.querySelectorAll('p')].find(x=>/titik dipilih|SEMUA pemain/.test(x.textContent)); return el?el.textContent.trim():null })
await tombol('Besarkan'); await wait(900)
const B = await posisi()
console.log(JSON.stringify({ teksPilihan: teks, jumlahBerubah: hitung(A,B), total: A.length, error: errs }, null, 2))
await b.close()
