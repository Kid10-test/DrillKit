import puppeteer from 'puppeteer'
import fs from 'node:fs'
const wait = (ms) => new Promise((r) => setTimeout(r, ms))
fs.mkdirSync('/home/user/shots', { recursive: true })
const b = await puppeteer.launch({ headless: 'new', args: ['--no-sandbox', '--mute-audio'] })
const p = await b.newPage(); await p.setViewport({ width: 1500, height: 1000 })
await p.goto('http://localhost:5173/', { waitUntil: 'networkidle2' }); await wait(1600)
await p.evaluate(() => { const x=[...document.querySelectorAll('button')].find(y=>y.textContent.includes('Muat data contoh')); x&&x.click() })
await wait(3400)
await p.evaluate(() => { location.hash = '#/drill' }); await wait(2800)
const toggle = (t) => p.evaluate((teks)=>{ const el=[...document.querySelectorAll('button,label')].find(x=>x.textContent.trim()===teks); if(el){el.click();return true} return false }, t)
await toggle('Warnai jejak menurut kesulitan'); await wait(1000)
await p.screenshot({ path: '/home/user/shots/dd3-analitik.png' })
console.log('selesai')
await b.close()
